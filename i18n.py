def normalize_language(value: Optional[str], default_language: str = "zh") -> str:
    if not value:
        return default_language
    normalized = LANGUAGE_INPUTS.get(value.strip().lower())
    return normalized or default_language


def is_supported_language(value: Optional[str]) -> bool:
    if not value:
        return False
    return value.strip().lower() in LANGUAGE_INPUTS


def get_language_name(language: str) -> str:
    return SUPPORTED_LANGUAGE_NAMES.get(language, language)


def t(language: str, key: str, **kwargs) -> str:
    templates = MESSAGES.get(language) or MESSAGES["zh"]
    template = templates.get(key) or MESSAGES["zh"].get(key) or key
    return template.format(**kwargs)
